// Builds apps/api/migrations/0001_init.sql from the DDL in the master plan v1.1 (section 11).
// The plan is the source of truth until Drizzle schema files replace it (gate S-3 decides the final form).
// Usage: node scripts/build-migration.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const plan = fs.readFileSync(path.join(root, 'CIRCULAR2ACTION_MASTER_PLAN_v1.1.md'), 'utf8');

const start = plan.indexOf('### 11.3 Identity and access');
const end = plan.indexOf('### 11.13 Later-phase tables');
const section2 = plan.slice(
  plan.indexOf('### 11.21 Tables added in v1.1'),
  plan.indexOf('## 12. API specification'),
);
const text = plan.slice(start, end) + '\n' + section2;

const blocks = [...text.matchAll(/```sql\n([\s\S]*?)```/g)].map((m) => m[1]);
const sql = blocks.join('\n');

const TS =
  'created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),\n  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)';
const CT = 'created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)';

// Tables that belong to later phases or depend on gate decisions (plan section 11 phase tags).
const EXCLUDED = new Set([
  'oauth_accounts', // P1
  'opportunity_views', // P1
  'cv_versions', // P1
  'generated_documents', // P1
  'application_documents', // P1
  'opportunity_embeddings', // P2 (VECTOR)
  'opportunity_terms', // only if gate S-1 selects the n-gram fallback
]);

// Split into statements at semicolons outside parentheses and comments.
function splitStatements(src) {
  const out = [];
  let buf = '';
  let depth = 0;
  let inLine = false;
  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    const n = src[i + 1];
    if (inLine) {
      buf += c;
      if (c === '\n') inLine = false;
      continue;
    }
    if (c === '-' && n === '-') {
      inLine = true;
      buf += c;
      continue;
    }
    if (c === '(') depth++;
    if (c === ')') depth--;
    if (c === ';' && depth === 0) {
      out.push(buf.trim());
      buf = '';
      continue;
    }
    buf += c;
  }
  if (buf.trim()) out.push(buf.trim());
  return out;
}

const statements = splitStatements(sql).filter((s) => /CREATE (TABLE|VIEW)/.test(s));
const tables = [];
const views = [];
for (let s of statements) {
  // macros are expanded only in code, never inside comments
  s = s
    .split('\n')
    .map((line) => {
      const i = line.indexOf('--');
      const code = i >= 0 ? line.slice(0, i) : line;
      const comment = i >= 0 ? line.slice(i) : '';
      return code.replace(/\bTS\b/g, TS).replace(/\bCT\b/g, CT) + comment;
    })
    .join('\n');
  // macro as final column (followed directly by newline + closing paren is handled by comma removal below)
  const name = /CREATE TABLE (\w+)/.exec(s)?.[1];
  if (/CREATE VIEW/.test(s)) {
    views.push(s);
    continue;
  }
  if (!name || EXCLUDED.has(name)) continue;
  // FK clauses that point at excluded tables are dropped (their tables are not created in this migration)
  s = s.replace(
    /,\s*CONSTRAINT \w+ FOREIGN KEY \(\w+\) REFERENCES (\w+)\(\w+\)[^,)]*(?=,|\n\))/g,
    (m, ref) => (EXCLUDED.has(ref) ? '' : m),
  );
  tables.push({
    name,
    sql: s,
    refs: [...s.matchAll(/REFERENCES (\w+)\(/g)].map((m) => m[1]).filter((r) => r !== name),
  });
}

// Topological sort by FK dependency.
const byName = new Map(tables.map((t) => [t.name, t]));
const ordered = [];
const state = new Map();
function visit(t, stack = []) {
  if (state.get(t.name) === 2) return;
  if (state.get(t.name) === 1) throw new Error(`FK cycle: ${[...stack, t.name].join(' -> ')}`);
  state.set(t.name, 1);
  for (const r of t.refs) {
    const dep = byName.get(r);
    if (!dep) throw new Error(`Table ${t.name} references missing table ${r}`);
    visit(dep, [...stack, t.name]);
  }
  state.set(t.name, 2);
  ordered.push(t);
}
for (const t of tables) visit(t);

const header = `-- GENERATED by scripts/build-migration.mjs from CIRCULAR2ACTION_MASTER_PLAN_v1.1.md (section 11). Do not edit by hand.
-- STATUS: PROVISIONAL. Not yet applied to any database. Gate S-3 (TiDB compatibility) must pass before this is trusted.
-- Target: TiDB (MySQL protocol), utf8mb4. Tables: ${ordered.length} (P0 set). View: ${views.length}.
-- Excluded on purpose: ${[...EXCLUDED].join(', ')}.
SET NAMES utf8mb4;
`;
const body = ordered.map((t) => t.sql + ';').join('\n\n');
const viewSql = views.map((v) => v + ';').join('\n\n');
const outFile = path.join(root, 'apps', 'api', 'migrations', '0001_init.sql');
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, `${header}\n${body}\n\n${viewSql}\n`);
console.log(
  `wrote ${path.relative(root, outFile)}: ${ordered.length} tables, ${views.length} view(s)`,
);
